"""OJEPH web console: talk to it, and watch the OJEPH model train.

    python web/server.py            # http://localhost:8000

Two engines are shown side by side, labelled honestly:
  * Live line  — interim engine (ElevenLabs agent in Jephthah's voice) so the
                 product can be demoed today. This one is a cascade, not OJEPH.
  * OJEPH lab  — the real native voice-to-voice model: live training loss and
                 audio generated by each new checkpoint, so you can hear it improve.

Env: ELEVENLABS_API_KEY, ELEVENLABS_AGENT_ID, OJEPH_RUN_DIR (default runs/live)
"""

from __future__ import annotations

import json
import os
import sys
import urllib.parse
import urllib.request
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse, JSONResponse
from fastapi.staticfiles import StaticFiles

ROOT = Path(__file__).resolve().parent
RUN = Path(os.environ.get("OJEPH_RUN_DIR", ROOT.parent / "runs" / "live"))
app = FastAPI(title="OJEPH console")


@app.get("/")
def index():
    return FileResponse(ROOT / "static" / "index.html")


@app.get("/api/signed-url")
def signed_url():
    key, agent = os.environ.get("ELEVENLABS_API_KEY"), os.environ.get("ELEVENLABS_AGENT_ID")
    if not key or not agent:
        raise HTTPException(503, "live engine not configured")
    url = ("https://api.elevenlabs.io/v1/convai/conversation/get-signed-url?agent_id="
           + urllib.parse.quote(agent))
    req = urllib.request.Request(url, headers={"xi-api-key": key})
    with urllib.request.urlopen(req, timeout=20) as r:
        return JSONResponse(json.load(r))


@app.get("/api/lab")
def lab():
    log = RUN / "train_log.jsonl"
    rows = []
    if log.exists():
        for line in log.read_text().splitlines()[-2000:]:
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    samples = []
    sdir = RUN / "samples"
    if sdir.exists():
        for meta in sorted(sdir.glob("*.json"), key=lambda p: p.stat().st_mtime, reverse=True)[:12]:
            try:
                m = json.loads(meta.read_text())
                m["url"] = f"/samples/{meta.with_suffix('.wav').name}"
                samples.append(m)
            except json.JSONDecodeError:
                pass
    status = {}
    if (RUN / "status.json").exists():
        status = json.loads((RUN / "status.json").read_text())
    return {"log": rows, "samples": samples, "status": status}


(RUN / "samples").mkdir(parents=True, exist_ok=True)
app.mount("/samples", StaticFiles(directory=RUN / "samples"), name="samples")
app.mount("/assets", StaticFiles(directory=ROOT.parent / "assets"), name="assets")


if __name__ == "__main__":
    import uvicorn

    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8000
    uvicorn.run(app, host="0.0.0.0", port=port, log_level="warning")
